import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {resolve} from 'node:path';

const root=resolve(import.meta.dirname,'..');
const ui=readFileSync(resolve(root,'src/ui.js'),'utf8');
const core=readFileSync(resolve(root,'src/core.js'),'utf8');
const shell=readFileSync(resolve(root,'src/shell.html'),'utf8');
if(!shell.includes('.battle .log:not(.expanded) .log-entry:not(:last-child){display:none}')) throw new Error('compact battle log must target current entry buttons');
const fn=ui.match(/function renderBattleLog\(\)\{[\s\S]*?\n\}/)?.[0];
if(!fn||!core.includes('run.log = [...(run.log||[]), ...log].slice(-80)')) throw new Error('battle log retention missing');
const state={st:{run:{log:Array.from({length:83},(_,i)=>`記録${i+1}`)}},sheetData:{page:0}};
const render=runInNewContext(`${fn}\nrenderBattleLog`,{G:state,esc:s=>String(s)});
const newest=render();
if(!newest.includes('直近80件')||!newest.includes('記録83')||newest.includes('記録3</p>')||!newest.includes('1/10ページ')) throw new Error('recent page or 80-entry cap failed');
state.sheetData.page=9;
const oldest=render();
if(!oldest.includes('10/10ページ')||!oldest.includes('記録4')||oldest.includes('記録3</p>')) throw new Error('oldest page includes discarded entries');
state.sheetData={page:9,line:79};
if(!render().includes('記録4')||!render().includes('履歴に戻る')) throw new Error('selected older log entry missing');
state.st.run.log=[];state.sheetData.page=99;
delete state.sheetData.line;
if(!render().includes('まだありません。')||!render().includes('1/1ページ')) throw new Error('empty or stale page failed');
const actionDef=ui.match(/const ACT = \{[\s\S]*?\n\};/)?.[0];
if(!actionDef) throw new Error('battle log action missing');
const view={st:{run:{log:[]}},screen:'battle',sheet:null,dlg:null,auto:true,autoT:null,autoLast:{},cmd:{stale:true},cursorSig:'auto',logExpanded:false};
let renders=0;
const expand=runInNewContext(`${actionDef}\nACT.battleLogExpand`,{G:view,render:()=>{renders++;},clearTimeout:()=>{}});
expand();
if(!view.logExpanded||view.auto||view.autoLast!==null||Object.keys(view.cmd).length||view.cursorSig!==null||renders!==1) throw new Error('expanding log did not stop auto mode');
view.sheet='battleLog';expand();
if(!view.logExpanded||renders!==1) throw new Error('log expanded behind a sheet');
view.st.run.log=['一','二'];view.sheet=null;
const actions=runInNewContext(`${actionDef}\nACT`,{G:view,render:()=>{renders++;},clearTimeout:()=>{}});
actions.battleLogLine({dataset:{v:'1'}});
if(view.sheet!=='battleLog'||view.sheetData.line!==0||renders!==2) throw new Error('log entry did not open its full text');
actions.battleLogBack();
if(view.sheetData.line!==undefined||view.sheetData.page!==0||renders!==3) throw new Error('log detail did not return to its page');
console.log('Battle log: 80-entry retention, newest/oldest pages, empty state OK');
