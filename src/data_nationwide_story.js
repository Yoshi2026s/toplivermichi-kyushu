function nationwideBossCycle(q,index){
  const single={t:"s",p:12+q}, spread={t:"a",p:6+Math.floor(q/2)};
  const charge={t:"c",p:0}, heavy={t:index%2?"s":"a",p:10+3*q,heavy:true};
  const patterns=[
    [single,spread,charge,heavy],
    [spread,single,spread,charge,heavy],
    [single,single,charge,heavy],
    [spread,charge,heavy,single],
    [single,spread,single,charge,heavy],
    [spread,spread,charge,heavy,single]
  ];
  return patterns[index%patterns.length].map(step=>({...step}));
}

