import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {resolve} from 'node:path';

const root=resolve(import.meta.dirname,'..');
const files=['data_enemies.js','data_saga_enemies.js','data_items.js','data_national.js','data.js','core.js'];
const source=files.map(f=>readFileSync(resolve(root,'src',f),'utf8')).join('\n');
const game=runInNewContext(`${source}\n({newGame,createFieldRun,aiCandidates,aiChoose,aiItemUseful,applyAction})`);
const fail=msg=>{throw new Error(msg)};
const st=game.newGame('確認用','女性');
st.bag=[{id:'IT001',n:1},{id:'IT057',n:1},{id:'IT071',n:1},{id:'IT058',n:1}];
const run=game.createFieldRun(st,'KY01-A1',{count:0,picks:[0,0]});
const actor=run.party.find(m=>m.hp>0);
const fullHP=actor.maxHP;
actor.maxHP=1000; actor.hp=500;
if(game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:20}],cgain:[]})||!game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:30}],cgain:[]})||!game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:1,revive:true}],cgain:[]})) fail('minimum recovery usefulness failed');
actor.hp=999;
if(!game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:1}],cgain:[]})) fail('small remaining shortage must count');
actor.maxHP=fullHP; actor.hp=fullHP;
const items=()=>game.aiCandidates(run,actor).filter(a=>a.type==='item');
if(items().length) fail('healthy party must not spend items');
actor.hp=Math.floor(actor.maxHP*0.8);
if(!items().some(a=>a.item==='IT001')||items().some(a=>['IT071','IT058'].includes(a.item))) fail('recovery candidate filter failed');
const before=JSON.stringify(run);
game.aiChoose(run);
if(JSON.stringify(run)!==before) fail('candidate search mutated battle state');
const used=game.applyAction(run,actor.pos,{type:'item',item:'IT001',ally:actor.pos});
if(!used.ok||run.itemHistory?.length!==1||run.itemHistory[0].hp<=0||run.itemHistory[0].c!==0||run.bag.find(e=>e.id==='IT001')) fail('confirmed item use was not recorded once');
const record=JSON.stringify(run.itemHistory);
game.aiChoose(run);
if(JSON.stringify(run.itemHistory)!==record) fail('auto search changed item history');
actor.hp=0;
if(!items().some(a=>a.item==='IT057')||items().some(a=>a.item==='IT058')) fail('revival candidate filter failed');
const danger=game.createFieldRun(st,'KY01-A1',{count:0,picks:[0,0]});
danger.party[0].hp=0;
danger.enemies[0].hp=999; danger.enemies[0].maxHP=999;
danger.enemies[0].cycle=[{t:'a',p:999}];
const dangerousPick=game.aiChoose(danger);
if(dangerousPick?.act.type==='item') fail('auto should not spend an item when the enemy immediately downs the party');
console.log('Auto items: thresholds, purchasable recovery and immutable search OK');
