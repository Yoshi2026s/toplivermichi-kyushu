import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {runInNewContext} from 'node:vm';

const root=resolve(import.meta.dirname,'..');
const core=['data_enemies.js','data_saga_enemies.js','data_items.js','data_national.js','data.js','core.js'].map(name=>readFileSync(resolve(root,'src',name),'utf8')).join('\n');
const ui=readFileSync(resolve(root,'src','ui.js'),'utf8');
const game=runInNewContext(`${core}\n({newGame,transferVaultGold})`);
const st=game.newGame('金庫確認','女性');
if(st.vaultGold!==0) throw new Error('new save vault must start empty');
st.gold=35510;
if(!game.transferVaultGold(st,'deposit',35510)||st.gold!==0||st.vaultGold!==35510) throw new Error('full deposit failed');
if(!game.transferVaultGold(st,'withdraw',1000)||st.gold!==1000||st.vaultGold!==34510) throw new Error('withdraw failed');
const before=JSON.stringify([st.gold,st.vaultGold]);
for(const [mode,n] of [['deposit',0],['deposit',-1],['deposit',1.5],['deposit',1001],['withdraw',34511],['other',1]]) if(game.transferVaultGold(st,mode,n)) throw new Error(`invalid transfer accepted: ${mode} ${n}`);
if(JSON.stringify([st.gold,st.vaultGold])!==before) throw new Error('rejected transfer changed balance');
const amountFn=ui.match(/function vaultAmountValue\(raw,from,to\)\{[\s\S]*?\n\}/)?.[0];
if(!amountFn) throw new Error('vault amount validator missing');
const amount=runInNewContext(`${amountFn}\nvaultAmountValue`);
if(amount('35510',35510,0)!==35510||amount('1',1,0)!==1) throw new Error('valid amount rejected');
for(const raw of ['', '0', '-1', '1.5', '1e3', 'abc', ' 1 ', '9007199254740992']) if(amount(raw,35510,0)!==0) throw new Error(`invalid amount accepted: ${raw}`);
if(amount('2',1,0)!==0||amount('1',1,Number.MAX_SAFE_INTEGER)!==0) throw new Error('balance or integer overflow accepted');
const migration=ui.match(/function migrate\(s\)\{[\s\S]*?\n\}/)?.[0];
if(!migration) throw new Error('save migration missing');
const migrate=runInNewContext(`${core}\nfunction soundPref(){return true}\n${migration}\nmigrate`);
const legacy=game.newGame('旧記録','男性'); delete legacy.vaultGold; legacy.gold=317;
const migrated=migrate(legacy);
if(migrated.vaultGold!==0||migrated.gold!==317) throw new Error('legacy gold migration failed');
const actDef=ui.match(/const ACT = \{[\s\S]*?\n\};/)?.[0], checksumDef=ui.match(/function checksum\(str\)\{[^\n]+/)?.[0];
if(!actDef||!checksumDef) throw new Error('vault action source missing');
const uiState={st:game.newGame('操作確認','女性'),sheetData:{mode:'deposit',amount:'',preview:null}};
uiState.st.gold=35510;
let input='35510', commits=0;
const actions=runInNewContext(`${checksumDef}\n${actDef}\nACT`,{G:uiState,$:()=>({value:input}),canEditVault:()=>true,vaultAmountValue:amount,transferVaultGold:game.transferVaultGold,render:()=>{},toast:()=>{},commit:()=>{commits++;uiState.st.saveGeneration++;}});
actions.vaultPreview();
const preview=uiState.sheetData.preview;
if(preview?.afterGold!==0||preview.afterVault!==35510) throw new Error('vault preview balance failed');
input='35509';actions.vaultCommit({dataset:{token:preview.token},disabled:false});
if(uiState.st.gold!==35510||commits!==0) throw new Error('changed input bypassed confirmation');
input='35510';const button={dataset:{token:preview.token},disabled:false};actions.vaultCommit(button);
if(uiState.st.gold!==0||uiState.st.vaultGold!==35510||commits!==1||!button.disabled) throw new Error('confirmed vault transfer failed');
actions.vaultCommit({dataset:{token:preview.token},disabled:false});
if(commits!==1||uiState.st.vaultGold!==35510) throw new Error('stale vault confirmation repeated transfer');
console.log('Gold vault: full deposit, withdrawal, invalid amounts and legacy save OK');

