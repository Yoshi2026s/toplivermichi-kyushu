import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {resolve} from 'node:path';

const root=resolve(import.meta.dirname,'..');
const files=['data_enemies.js','data_saga_enemies.js','data_items.js','data_national.js','data.js','core.js'];
const source=files.map(f=>readFileSync(resolve(root,'src',f),'utf8')).join('\n');
const game=runInNewContext(`${source}\n({newGame,createFieldRun,aiCandidates,aiChoose,aiItemUseful,itemBattleBadges,growthBattleBadges,applyAction})`);
const fail=msg=>{throw new Error(msg)};
const st=game.newGame('確認用','女性');
st.bag=[{id:'IT001',n:1},{id:'IT057',n:1},{id:'IT071',n:1},{id:'IT058',n:1}];
const run=game.createFieldRun(st,'KY01-A1',{count:0,picks:[0,0]});
if(!Array.isArray(run.itemHistory)||run.itemHistory.length||run.itemHistoryComplete!==true) fail('new battle history must start empty');
const badges=h=>Array.from(game.itemBattleBadges(h)).join(',');
if(badges([])!=='B081'||badges([{id:'IT001',hp:1,c:0}])!=='B082,B083'||badges([{id:'IT001',hp:1,c:0},{id:'IT002',hp:0,c:1}])!=='B083,B084,B085') fail('item badge victory conditions failed');
const badgeRun=game.createFieldRun(st,'KY01-A1',{count:0,picks:[0,0]});
badgeRun.A=80;
const badgeWith=(history,flags)=>Array.from(game.itemBattleBadges(history,{...badgeRun,actionFlags:{...badgeRun.actionFlags,...flags}})).join(',');
if(badgeWith([],{skillUsed:true,mpRestored:true})!=='B081,B086,B087,B088,B089') fail('no-item action badges failed');
if(badgeWith([{id:'IT001'}],{cheerSpent:true,guardUsed:true})!=='B082,B083,B087,B090') fail('item and guard badges failed');
if(Array.from(game.itemBattleBadges([],{...badgeRun,actionHistoryComplete:false})).join(',')!=='B081') fail('incomplete action history awarded action badges');
const guardActor=badgeRun.party[0];
if(!game.applyAction(badgeRun,guardActor.pos,{type:'guard'}).ok||!badgeRun.actionFlags.guardUsed||!badgeRun.actionFlags.mpRestored) fail('confirmed guard action not recorded');
if(game.applyAction(badgeRun,guardActor.pos,{type:'guard'}).ok!==false) fail('duplicate action should be rejected');
const growth=run=>Array.from(game.growthBattleBadges(run)).join(',');
if(growth(badgeRun)!=='B091'||growth({...badgeRun,kind:'boss',actionHistoryComplete:false})!=='B092') fail('victory kind badges failed');
const growthRun={...badgeRun,actionFlags:{...badgeRun.actionFlags,actors:['hero','moe'],jobs:['J01','J02','J03'],revived:true}};
if(growth(growthRun)!=='B091,B094,B095,B096'||growth({...growthRun,party:[{hp:0}]})!=='B091,B094,B095') fail('growth action badges failed');
if(growth({...growthRun,actionFlags:{...growthRun.actionFlags,lowHeal:true}})!=='B091,B094,B095,B096,B097') fail('low HP recovery badge failed');
if(growth({...growthRun,kind:'boss',actionFlags:{...growthRun.actionFlags,cueSolved:true}})!=='B092,B094,B095,B096,B098') fail('boss counter badge failed');
const lowRun=game.createFieldRun(st,'KY01-A1',{count:0,picks:[0,0]});
lowRun.party[0].hp=Math.floor(lowRun.party[0].maxHP*0.3);
lowRun.bag=[{id:'IT001',n:1}];
if(!game.applyAction(lowRun,0,{type:'item',item:'IT001',ally:0}).ok||!lowRun.actionFlags.lowHeal) fail('confirmed critical recovery not tracked');
const actor=run.party.find(m=>m.hp>0);
const fullHP=actor.maxHP;
actor.maxHP=1000; actor.hp=500;
if(game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:20}],cgain:[]})||!game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:30}],cgain:[]})||!game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:1,revive:true}],cgain:[]})) fail('minimum recovery usefulness failed');
actor.hp=999;
if(!game.aiItemUseful(run,{heal:[{pos:actor.pos,amt:1}],cgain:[]})) fail('small remaining shortage must count');
actor.maxHP=fullHP; actor.hp=fullHP;
const items=()=>game.aiCandidates(run,actor).filter(a=>a.type==='item');
if(items().length) fail('healthy party must not spend items');
actor.hp=Math.floor(actor.maxHP*0.8);
if(!items().some(a=>a.item==='IT001')||items().some(a=>['IT071','IT058'].includes(a.item))) fail('recovery candidate filter failed');
const before=JSON.stringify(run);
game.aiChoose(run);
if(JSON.stringify(run)!==before) fail('candidate search mutated battle state');
run.itemHistory={}; // 旧記録や壊れた記録でも確定した使用を続行する
const used=game.applyAction(run,actor.pos,{type:'item',item:'IT001',ally:actor.pos});
if(!used.ok||run.itemHistory?.length!==1||run.itemHistory[0].hp<=0||run.itemHistory[0].c!==0||run.bag.find(e=>e.id==='IT001')) fail('confirmed item use was not recorded once');
const record=JSON.stringify(run.itemHistory);
game.aiChoose(run);
if(JSON.stringify(run.itemHistory)!==record) fail('auto search changed item history');
actor.hp=0;
if(!items().some(a=>a.item==='IT057')||items().some(a=>a.item==='IT058')) fail('revival candidate filter failed');
const danger=game.createFieldRun(st,'KY01-A1',{count:0,picks:[0,0]});
danger.party[0].hp=0;
danger.enemies[0].hp=999; danger.enemies[0].maxHP=999;
danger.enemies[0].cycle=[{t:'a',p:999}];
const dangerousPick=game.aiChoose(danger);
if(dangerousPick?.act.type==='item') fail('auto should not spend an item when the enemy immediately downs the party');
console.log('Auto items: thresholds, purchasable recovery and immutable search OK');

