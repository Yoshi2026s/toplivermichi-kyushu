import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {runInNewContext} from 'node:vm';

const root=resolve(import.meta.dirname,'..');
const files=['data_enemies.js','data_saga_enemies.js','data_items.js','data_national.js','data.js','core.js'];
const core=files.map(f=>readFileSync(resolve(root,'src',f),'utf8')).join('\n');
const ui=readFileSync(resolve(root,'src','ui.js'),'utf8');
const section=ui.slice(ui.indexOf('const PENDING_BADGES='),ui.indexOf('function renderRecord(){'));
const G={sheetData:{}};
const catalog=runInNewContext(`${core}\n${section}\n({PENDING_BADGES,BADGE_GROUPS,renderBadgeRecord,renderBattleChallenges})`,{G,esc:s=>String(s)});
const ids=Array.from({length:100},(_,i)=>`B${String(i+1).padStart(3,'0')}`);
const implemented={...runInNewContext(`${core}\n({ITEM_BADGES,GROWTH_BADGES,PARTY_BADGES,ACTION_BADGES,HEAL_BADGES,MP_BADGES,CHEER_BADGES,SPEED_BADGES,ATTACK_BADGES,GUARD_BADGES,DEFENSE_BADGES})`)};
const all=new Set([...Object.keys(catalog.PENDING_BADGES),...Object.values(implemented).flatMap(Object.keys)]);
if(all.size!==100||ids.some(id=>!all.has(id))||Object.keys(catalog.PENDING_BADGES).length!==16||catalog.BADGE_GROUPS.length!==10) throw new Error('badge catalog must cover exactly B001-B100');
const st={battleBadges:['B001','B071']};
const full=catalog.renderBadgeRecord(st);
if(!full.includes('獲得2/100種')||!full.includes('B001')||!full.includes('B100')||!full.includes('― 制作中 B072')) throw new Error('full badge record failed');
G.sheetData.badgeOnlyUnowned=true;
const missing=catalog.renderBadgeRecord(st);
if(missing.includes('● 獲得済み B001')||!missing.includes('B100')||!missing.includes('すべて表示')) throw new Error('missing badge filter failed');
G.st={battleBadges:[],run:{kind:'field',turn:2,state:'input',A:0,kiraDone:false,party:[{cid:'hero',hp:10,maxHP:10,c:5}],itemHistory:[],itemHistoryComplete:true,actionFlags:{attackHit:true,actionCount:2,enemyAttacked:true,restUsed:false,cheerSpent:false},actionHistoryComplete:true}};
let live=catalog.renderBattleChallenges();
if(!live.includes('勝利で確定・B011')||!live.includes('今回達成不可・B001')||!live.includes('今回達成不可・B005')||!live.includes('今回達成不可・B007')||!live.includes('対象外・B008')||!live.includes('対象外・B023')||!live.includes('制作中・B009')||!live.includes('速攻（今回の対象 8件）')||!live.includes('B021 多彩な作戦')||!live.includes('B021 多彩な作戦（0/3）')) throw new Error('live challenge statuses failed');
G.st.run.itemHistory=[{id:'IT01'}];
live=catalog.renderBattleChallenges();
if(!live.includes('今回達成不可・B081')||!live.includes('勝利で確定・B083')) throw new Error('item challenge statuses failed');
G.st.run.actionHistoryComplete=false;
live=catalog.renderBattleChallenges();
if(live.includes('勝利で確定・B011')) throw new Error('incomplete action history must not confirm badge');
if(live.includes('B021 多彩な作戦（0/3）')) throw new Error('incomplete action history must not show inferred progress');
G.st.run.turn=1;G.st.run.actionHistoryComplete=true;G.st.battleBadges=['B001','B002','B011','B021','B023','B031','B041','B061','B081'];
live=catalog.renderBattleChallenges();
if(live.includes('B001 開幕の決着：')||live.includes('B011 基本の一撃：')||live.includes('B081 道具を温存：')) throw new Error('owned or impossible badges recommended');
G.sheetData.onlyActionable=true;
live=catalog.renderBattleChallenges();
if(!live.includes('すべて表示')||live.includes('獲得済み・B001')||live.includes('制作中・B009')||live.includes('今回達成不可・B081')||!live.includes('未達成・B003')) throw new Error('actionable challenge filter failed');
G.sheetData.onlyActionable=false;G.st.battleBadges=[];G.st.run.state='lost';
live=catalog.renderBattleChallenges();
if(!live.includes('今回達成不可・B011')||live.includes('勝利で確定・B011')||!live.includes('今おすすめできる未達成の条件はありません')) throw new Error('lost battle challenge status failed');
console.log('Badge catalog: 100 IDs, 10 groups, live progress, recommendations and filter OK');

