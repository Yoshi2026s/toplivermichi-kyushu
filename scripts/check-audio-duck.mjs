import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {resolve} from 'node:path';

const source=readFileSync(resolve(import.meta.dirname,'../src/audio.js'),'utf8');
const duck=source.match(/function duckBgm\(duration\)\{[\s\S]*?\n  \}/)?.[0];
const stop=source.match(/function stopBgm\(\)\{[^\n]+\}/)?.[0];
const output=source.match(/function outputLevel\(value,time\)\{[\s\S]*?\n  \}/)?.[0];
const mix=source.slice(source.indexOf('  function holdGain'),source.indexOf('  function setVolumes'));
if(!mix||!duck||!stop||!output) throw new Error('audio gain functions missing');
const calls=[];
const gain={value:0.5,cancelAndHoldAtTime:t=>calls.push(['hold',t]),cancelScheduledValues:t=>calls.push(['cancel',t]),setValueAtTime:(v,t)=>calls.push(['set',v,t]),linearRampToValueAtTime:(v,t)=>calls.push(['ramp',v,t])};
const state={currentTime:10};
const sound=runInNewContext(`let ac=state,musicBus={gain},timer=1,duckUntil=0,musicVolume=1,revOutput=null,delayOutput=null;const musicGain=()=>.5,stopSources=()=>{};${mix}\n${duck}\n${stop}\n({duckBgm,stopBgm})`,{state,gain,clearInterval:()=>{}});
sound.duckBgm(0.2);
if(!calls.some(c=>c[0]==='ramp'&&c[1]===0.5&&Math.abs(c[2]-10.58)<1e-6)) throw new Error('BGM did not recover after effect');
state.currentTime=10.1;calls.length=0;sound.duckBgm(0.3);
if(!calls.some(c=>c[0]==='ramp'&&c[1]===0.5&&Math.abs(c[2]-10.78)<1e-6)) throw new Error('overlapping effect restored BGM too early');
calls.length=0;sound.stopBgm();
if(!calls.some(c=>c[0]==='ramp'&&c[1]===0.5&&Math.abs(c[2]-10.125)<1e-6)) throw new Error('stopping BGM did not reset gain');
const masterCalls=[];
const master={gain:{value:0.85,cancelAndHoldAtTime:t=>masterCalls.push(['hold',t]),linearRampToValueAtTime:(v,t)=>masterCalls.push(['ramp',v,t])}};
const outputLevel=runInNewContext(`let ac=state,master=masterNode;${output}\noutputLevel`,{state,masterNode:master});
outputLevel(0.0001,0.03);
if(!masterCalls.some(c=>c[0]==='ramp'&&c[1]===0.0001&&Math.abs(c[2]-10.13)<1e-6)) throw new Error('mute did not fade output');
masterCalls.length=0;outputLevel(0.85,0.06);
if(!masterCalls.some(c=>c[0]==='ramp'&&c[1]===0.85&&Math.abs(c[2]-10.16)<1e-6)) throw new Error('unmute did not restore output');
console.log('Audio: short duck, overlapping effects, stop reset, mute/unmute gain OK');
const setOn=source.match(/function setOn\(v\)\{[\s\S]*?\n  \}/)?.[0];
const suspend=source.match(/function suspend\(\)\{[^\n]+\}/)?.[0];
if(!setOn||!suspend) throw new Error('audio state functions missing');
const events=[];
const controls=runInNewContext(`const effectLast=new Map();let ac={state:'running',suspend:()=>Promise.resolve()},on=true,cur='battle',jingleT=4;const stopSources=()=>{},init=()=>true,outputLevel=()=>events.push('level'),play=()=>events.push('play'),stopBgm=()=>events.push('stop');${setOn}\n${suspend}\n({setOn,suspend,get timer(){return jingleT}})`,{events,clearTimeout:()=>events.push('clear')});
controls.setOn(true);
if(events.length) throw new Error('repeated enable restarted audio');
controls.setOn(false);
if(events.join(',')!=='clear,stop,level'||controls.timer!==null) throw new Error('mute left jingle scheduled');
events.length=0;controls.setOn(false);
if(events.length) throw new Error('repeated mute changed audio');
controls.setOn(true);
if(events.join(',')!=='level,play') throw new Error('unmute did not resume destination music');
events.length=0;controls.suspend();
if(events.join(',')!=='stop') throw new Error('suspend did not stop music');
console.log('Audio: repeated settings and jingle cancellation OK');
const resume=source.match(/function resume\(\)\{[^\n]+\}/)?.[0];
if(!resume) throw new Error('audio resume missing');
const resumes=[];
const resumed=runInNewContext(`let on=true,ac={state:'running',resume:()=>Promise.resolve()},cur='battle',timer=1,jingleT=null;const play=n=>resumes.push(n);${resume}\n({resume,stop:()=>{timer=null},get current(){return cur}})`,{resumes});
resumed.resume();
if(resumes.length) throw new Error('visible event restarted active BGM');
resumed.stop();resumed.resume();
if(resumes.join(',')!=='battle'||resumed.current!==null) throw new Error('suspended BGM did not resume once');
resumed.resume();
if(resumes.length!==1) throw new Error('repeated resume restarted BGM');
console.log('Audio: visibility resume is idempotent OK');
